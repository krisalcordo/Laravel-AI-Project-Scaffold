#!/usr/bin/env bash

set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
root=$(cd "$script_dir/.." && pwd)

# shellcheck source=.ddev/lib/project-settings.sh
source "$script_dir/lib/project-settings.sh"
load_scaffold_settings "$root"

slot_count=${1:-$PREVIEW_SLOT_COUNT}

if ! [[ "$slot_count" =~ ^[1-9][0-9]*$ ]] || [ "$slot_count" -gt 50 ]; then
    echo "Slot count must be an integer from 1 to 50" >&2
    exit 2
fi

output="$script_dir/config.preview.yaml"

{
    echo "# Generated by .ddev/generate-preview-slots.sh; do not edit by hand."
    echo "additional_hostnames:"
    for ((i = 1; i <= slot_count; i++)); do
        if [ "$i" -eq 1 ]; then
            echo "    - $PREVIEW_HOST_PREFIX"
        else
            echo "    - $PREVIEW_HOST_PREFIX-$i"
        fi
    done
    echo "web_extra_exposed_ports:"
    for ((i = 1; i <= slot_count; i++)); do
        port=$((PREVIEW_BASE_PORT + 2 * (i - 1)))
        echo "    - name: preview$i"
        echo "      container_port: $port"
        echo "      http_port: $port"
        echo "      https_port: $((port + 1))"
    done
} > "$output"

last_port=$((PREVIEW_BASE_PORT + 2 * slot_count - 1))
echo "Wrote $output with $slot_count slots on ports $PREVIEW_BASE_PORT-$last_port."
echo "Run 'ddev restart' to apply it."

